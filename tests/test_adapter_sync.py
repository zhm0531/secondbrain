import sys
from pathlib import Path

ROOT = Path(__file__).parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import sync_adapters  # noqa: E402


def test_adapters_match_shared_sources() -> None:
    """Every generated copy must be byte-identical to its shared source.

    Adapters are self-contained on purpose (each distribution channel installs
    only its own directory), so the copies are generated by
    ``tools/sync_adapters.py`` and this test is the drift guard:
    run ``python tools/sync_adapters.py`` instead of editing a copy by hand.
    """
    problems = sync_adapters.drift()
    assert problems == [], "adapter copies drifted from integrations/shared/ + skills/: " + "; ".join(problems)


def test_shared_mcp_server_is_executable_script() -> None:
    source = ROOT / "integrations" / "shared" / "secondbrain_mcp_server.py"
    first_line = source.read_text(encoding="utf-8").splitlines()[0]
    assert first_line.startswith("#!") and "python" in first_line


def test_adapters_only_add_transport_glue() -> None:
    """The agent-specific layer is manifests only: no core logic lives there."""
    codex = ROOT / "codex-plugin"
    dsh = ROOT / "integrations" / "deepseek-harness" / "dsh-secondbrain-bridge"

    codex_files = {p.relative_to(codex).as_posix() for p in codex.rglob("*") if p.is_file()}
    dsh_files = {p.relative_to(dsh).as_posix() for p in dsh.rglob("*") if p.is_file()}

    assert "mcp/secondbrain_mcp_server.py" in codex_files
    assert "scripts/secondbrain_mcp_server.py" in dsh_files
    # Core implementation must never be duplicated inside an adapter.
    assert not any(name.startswith("secondbrain_core/") for name in codex_files | dsh_files)
